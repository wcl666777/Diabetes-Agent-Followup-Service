"""问题类型的统一定义与规则兜底分类。

用途：告诉「生成模型」这道题该往哪个方向答（饮食 / 运动 / 用药 ...），
使回答更聚焦。两处共用同一套类别，保证 LLM 与规则兜底口径一致：
  - 意图识别 Agent（LLM 主导）：app/agents/intent_agent/
  - 规则兜底（零成本）：本模块 classify_question_type()
"""

# 统一的问题类型清单（LLM Prompt 与规则兜底必须保持一致）
QUESTION_TYPES = [
    "饮食",
    "运动",
    "用药",
    "血糖监测",
    "并发症",
    "生活方式",
    "就医指导",
]

# 无法归类时的默认类型
DEFAULT_QUESTION_TYPE = "综合咨询"

# 关键词 → 类型（列表顺序即匹配优先级）
_KEYWORDS = [
    ("饮食", ["吃", "饮食", "食物", "主食", "水果", "忌口", "营养", "食谱", "喝"]),
    ("运动", ["运动", "锻炼", "跑步", "散步", "健身", "活动量", "游泳", "骑车"]),
    ("用药", ["药", "胰岛素", "二甲双胍", "达格列净", "甘精", "剂量", "服药", "打针", "注射"]),
    ("血糖监测", ["监测", "测量", "测血糖", "空腹", "餐后", "睡前", "血糖值", "mmol", "糖化", "hba1c"]),
    ("并发症", ["并发症", "视网膜", "肾病", "神经病变", "糖尿病足", "酮症", "心脑血管"]),
    ("生活方式", ["作息", "熬夜", "戒烟", "喝酒", "体重", "减肥", "情绪", "焦虑", "睡眠"]),
    ("就医指导", ["复查", "复诊", "就医", "医院", "挂号", "检查", "化验"]),
]


def classify_question_type(question: str) -> str:
    """规则版问题类型识别（零额外调用）。

    定位：意图识别 Agent 的兜底 —— 大模型不可用 / 输出无法解析时使用，
    保证生成侧始终拿得到一个可用的类型。
    """
    for qtype, keywords in _KEYWORDS:
        if any(kw in question for kw in keywords):
            return qtype
    return DEFAULT_QUESTION_TYPE
